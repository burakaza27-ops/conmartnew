export function normalizeCategorySlug(input?: string | null): string {
  if (!input) return "";
  const cleaned = input
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");

  if (CATEGORY_IMAGES[cleaned]) return cleaned;
  if (cleaned.includes("cement")) return "cement";
  if (cleaned.includes("steel") || cleaned.includes("rebar")) return "steel";
  if (cleaned.includes("aggregate") || cleaned.includes("sand")) return "aggregates";
  if (cleaned.includes("ready") || cleaned.includes("concrete")) return "ready-mix-concrete";
  if (cleaned.includes("metal")) return "metal-works";
  if (cleaned.includes("alumin") || cleaned.includes("almun")) return "aluminium-works";
  if (cleaned.includes("glass")) return "glass";
  if (cleaned.includes("roof") || cleaned.includes("ega")) return "roofing";
  if (cleaned.includes("tile") || cleaned.includes("finish")) return "finishing-tiles";
  if (cleaned.includes("paint") || cleaned.includes("gypsum")) return "paints-gypsum";
  if (cleaned.includes("admixture") || cleaned.includes("chemical")) return "admixtures-chemicals";
  if (cleaned.includes("block") || cleaned.includes("hcb")) return "blocks";
  if (cleaned.includes("sanitary") || cleaned.includes("toilet") || cleaned.includes("basin")) return "sanitary-materials";
  if (cleaned.includes("plumb") || cleaned.includes("pipe")) return "plumbing";
  if (cleaned.includes("electr") || cleaned.includes("cable")) return "electrical";
  if (cleaned.includes("hardware") || cleaned.includes("tool")) return "hardware";
  if (cleaned.includes("hvac") || cleaned.includes("vent")) return "hvac-mechanical";
  if (cleaned.includes("infra") || cleaned.includes("landscap")) return "infrastructure-landscaping";
  if (cleaned.includes("wast") || cleaned.includes("reuse") || cleaned.includes("scrap")) return "reusable-site-wastage";
  if (cleaned.includes("other") || cleaned.includes("timber")) return "other-materials";

  return cleaned;
}

/**
 * Returns a relevant image URL for the given category slug or category name.
 * Falls back to a generic construction site photo if the slug is unknown.
 */
export function getCategoryImage(slugOrName: string, size: 600 | 800 | 1200 = 800): string {
  const normalized = normalizeCategorySlug(slugOrName);
  const base = CATEGORY_IMAGES[normalized] ?? CONSTRUCTION_FALLBACK;
  return base.replace("w=800", `w=${size}`);
}

/**
 * Generic fallback for construction materials that have no specific image.
 * Shows construction workers at a site — clearly industry-relevant.
 */
export const CONSTRUCTION_FALLBACK =
  "https://images.unsplash.com/photo-1504307651254-35680f356dfd?auto=format&fit=crop&w=800&q=80";

/**
 * Returns a relevant fallback for a specific product based on its category slug or name.
 * Used when a product/listing has no uploaded image.
 */
export function getProductFallback(categorySlugOrName?: string | null): string {
  const normalized = normalizeCategorySlug(categorySlugOrName);
  if (normalized && CATEGORY_IMAGES[normalized]) {
    return CATEGORY_IMAGES[normalized];
  }
  return CONSTRUCTION_FALLBACK;
}
